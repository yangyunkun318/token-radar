// Token radar model v1: a calibrated implied value, built only from the snapshot's own figures.
//
// The starter's flat TVL x 0.25 is replaced by a multiple calibrated on the market itself: for every
// category, the median market-cap/TVL of the protocols in that category that already trade, taken
// from this same snapshot. A category with too few traded names to trust falls back to the whole
// market's median. The multiple is clamped so one outlier protocol cannot set a category's price.
//
//   category_multiple = median(mcap_usd / tvl_usd) over traded protocols of the category
//                       (n >= 4, else the all-market median; clamped to [0.05, 1.00])
//   growth            = clamp(change_7d, -60, 120) per cent
//   growthMult        = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity          = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   implied           = max(1, round(tvl_usd x category_multiple x growthMult x maturity))
//
// No protocol name is ever special-cased: the same function scores every row, and the calibration
// table the dashboard shows is computed from the snapshot at run time, never typed in by hand.

